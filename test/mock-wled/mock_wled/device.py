    def device_id(self):
        """util.cpp getDeviceId shape: 40 hex digits plus 2 of a second hash."""
        first = hashlib.sha1(("mock-wled" + self.mac).encode()).hexdigest()
        return first + hashlib.sha1(first.encode()).hexdigest()[38:]


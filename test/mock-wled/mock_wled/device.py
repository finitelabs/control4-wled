def max_segments(version, chip, psram):
    if chip == "esp8266":
        return 16
    if chip == "esp32s2":
        return 32 if version == "16.0.1" else 20
    return 64 if (version == "16.0.1" and psram) else 32


def load_data(version, target):
    with open(DATA_DIR / version / f"{target}.json", encoding="utf-8") as f:
        return json.load(f)


# bus_manager.h Bus::hasRGB/hasWhite/hasCCT
def bus_has_rgb(t):
    return not (
        TYPE_WS2812_1CH <= t <= TYPE_WS2812_WWA
        or t in (TYPE_ANALOG_1CH, TYPE_ANALOG_2CH, TYPE_ONOFF)
    )


def bus_has_white(t):
    return (
        TYPE_WS2812_1CH <= t <= TYPE_WS2812_WWA
        or t in (TYPE_SK6812_RGBW, TYPE_TM1814, TYPE_UCS8904, TYPE_FW1906, TYPE_WS2805)
        or t == TYPE_SM16825
        or (TYPE_ONOFF < t <= TYPE_ANALOG_5CH and t != TYPE_ANALOG_3CH)
        or t in (TYPE_NET_DDP_RGBW, TYPE_NET_ARTNET_RGBW)
    )


def bus_has_cct(t, v16):
    cct = (
        TYPE_WS2812_WWA,
        TYPE_SM16825,
        TYPE_ANALOG_2CH,
        TYPE_ANALOG_5CH,
        TYPE_FW1906,
        TYPE_WS2805,
    )
    return t in cct or (not v16 and t == TYPE_WS2812_2CH_X3)


# ArduinoJson conversions as WLED uses them: `v | default` keeps the default unless the value
# is of the target type and fits it; `as<byte>()` gives 0 for a number that does not fit.
def _is_int(v):
    return isinstance(v, int) and not isinstance(v, bool)


def pipe_int(v, default, lo=-(2**31), hi=2**31 - 1):
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    return v if _is_int(v) and lo <= v <= hi else default


def pipe_u8(v, default):
    return pipe_int(v, default, 0, 255)


def pipe_u16(v, default):
    return pipe_int(v, default, 0, 65535)


def pipe_bool(v, default):
    return v if isinstance(v, bool) else default


def as_u8(v):
    return v if _is_int(v) and 0 <= v <= 255 else 0


def truthy(v):
    return bool(v) if isinstance(v, (bool, int, float)) else False


def parse_number(s, val, minv, maxv):
    """util.cpp parseNumber: "~" step, "~-" step down, "~N" offset, "w" wrap, "r" random, "A~B~"."""
    if not s:
        return val
    if s[0] == "r":
        return random.randint(minv, (maxv or 255) - 1) if (maxv or 255) > minv else minv
    wrap = False
    if s[0] == "w" and len(s) > 1:
        s, wrap = s[1:], True
    if s[0] == "~":
        out = _atoi(s[1:])
        if out == 0:
            if s[1:2] == "0":
                return val
            if s[1:2] == "-":
                return maxv if val - 1 < minv else min(maxv, val - 1)
            return minv if val + 1 > maxv else max(minv, val + 1)
        if wrap and val == maxv and out > 0:
            return minv
        if wrap and val == minv and out < 0:
            return maxv
        return max(minv, min(maxv, out + val))
    if minv == maxv == 0:
        p1 = _atoi(s)
        i = s.find("~")
        if i >= 0:
            rest = s[i + 1 :]
            p2 = _atoi(rest)
            if p2 > 0:
                j = 0
                while j < len(rest) and rest[j].isdigit():
                    j += 1
                return parse_number(rest[j:], val, p1, p2)
    return _atoi(s) & 0xFF


def _atoi(s):
    sign, i, n = 1, 0, 0
    s = s.lstrip()
    if s[:1] in "+-" and s:
        sign = -1 if s[0] == "-" else 1
        i = 1
    while i < len(s) and s[i].isdigit():
        n = n * 10 + int(s[i])
        i += 1
    return sign * n


def get_val(elem, val, vmin=0, vmax=255):
    """util.cpp getVal: returns (found, value)."""
    if _is_int(elem):
        if elem < 0:
            return False, val
        return True, as_u8(elem)
    if isinstance(elem, str):
        if len(elem) == 0 or len(elem) > 12:
            return False, val
        if len(elem) > 3 and ("r" in elem or elem.find("~") != elem.rfind("~")):
            vmin = vmax = 0
        return True, parse_number(elem, val, vmin, vmax)
    return False, val


def get_bool_val(elem, dflt):
    """util.cpp getBoolVal: "t" toggles the default."""
    if isinstance(elem, str) and elem[:1] == "t":
        return not dflt
    return pipe_bool(elem, dflt)


def rgbw32(r, g, b, w):
    return ((w & 0xFF) << 24) | ((r & 0xFF) << 16) | ((g & 0xFF) << 8) | (b & 0xFF)


def channels(c):
    return [(c >> 16) & 0xFF, (c >> 8) & 0xFF, c & 0xFF, (c >> 24) & 0xFF]


def color_from_hex(s):
    """colors.cpp colorFromHexString: 6 digits RRGGBB, 8 digits RRGGBBWW (W last)."""
    if len(s) not in (6, 8):
        return None
    n, i = 0, 0
    while i < len(s) and s[i] in "0123456789abcdefABCDEF":
        n = n * 16 + int(s[i], 16)
        i += 1
    if len(s) == 6:
        return [(n >> 16) & 0xFF, (n >> 8) & 0xFF, n & 0xFF, 0]
    return [(n >> 24) & 0xFF, (n >> 16) & 0xFF, (n >> 8) & 0xFF, n & 0xFF]


def hue_to_rgb(index):
    """colors.cpp colorHStoRGB at full saturation and value, for a 0-255 wheel index."""
    h = index * 360 / 256
    sector, frac = int(h // 60) % 6, (h % 60) / 60
    up, down = int(255 * frac), int(255 * (1 - frac))
    return [
        (255, up, 0),
        (down, 255, 0),
        (0, 255, up),
        (0, down, 255),
        (up, 0, 255),
        (255, 0, down),
    ][sector]


def color_k_to_rgb(kelvin):
    """colors.cpp colorKtoRGB."""
    import math

    temp = kelvin / 100.0
    if temp <= 66.0:
        r = 255
        g = round(99.4708025861 * math.log(temp) - 161.1195681661)
        b = 0 if temp <= 19.0 else round(138.5177312231 * math.log(temp - 10.0) - 305.0447927307)
    else:
        r = round(329.698727446 * (temp - 60.0) ** -0.1332047592)
        g = round(288.1221695283 * (temp - 60.0) ** -0.0755148492)
        b = 255
    return [max(0, min(255, r)), max(0, min(255, g)), max(0, min(255, b)), 0]


class MonotonicClock:
    def ms(self):
        return int(time.monotonic() * 1000)


class FakeClock:
    def __init__(self, start=100000):
        self.now = start

    def ms(self):
        return self.now

    def advance(self, ms):
        self.now += ms


class Bus:
    def __init__(self, cfg):
        self.type = cfg["type"]
        self.start = cfg.get("start", 0)
        self.len = cfg["len"]
        self.rgbwm = cfg.get("rgbwm", RGBW_MODE_MANUAL_ONLY)
        self.order = cfg.get("order", 0)

    def to_cfg(self):
        return {
            "start": self.start,
            "len": self.len,
            "type": self.type,
            "order": self.order,
            "rgbwm": self.rgbwm,
        }


class Segment:
    # Fields compared by WLED's differs() (json.cpp), selection excluded.
    COMPARED = (
        "start",
        "stop",
        "offset",
        "grouping",
        "spacing",
        "start_y",
        "stop_y",
        "mode",
        "palette",
        "opacity",
        "speed",
        "intensity",
        "custom1",
        "custom2",
        "custom3",
        "check1",
        "check2",
        "check3",
        "on",
        "freeze",
        "reverse",
        "mirror",
        "reverse_y",
        "mirror_y",
        "transpose",
        "map1d2d",
        "sound_sim",
        "set",
    )

    def __init__(self, start, stop, start_y=0, stop_y=1, color=0):
        self.start, self.stop, self.start_y, self.stop_y = start, stop, start_y, stop_y
        self.colors = [color, 0, 0]
        self.selected, self.on, self.freeze = True, True, False
        self.grouping, self.spacing, self.offset = 1, 0, 0
        self.opacity, self.cct = 255, 127
        self.mode, self.palette, self.speed, self.intensity = 0, 0, 128, 128
        self.custom1, self.custom2, self.custom3 = 128, 128, 16
        self.check1 = self.check2 = self.check3 = False
        self.reverse = self.mirror = self.reverse_y = self.mirror_y = self.transpose = False
        self.sound_sim, self.map1d2d, self.set, self.blend_mode = 0, 0, 0, 0
        self.name = None
        self.reset = False
        # A color transition (FX_fcn.cpp Segment::startTransition): the colors it fades from, its
        # start and its length; t_from None is no transition.
        self.t_from, self.t_start, self.t_dur = None, 0, 0

    def is_active(self):
        return self.stop > self.start

    def snapshot(self):
        return tuple(getattr(self, k) for k in self.COMPARED) + tuple(self.colors)

    def differs(self, snap):
        return self.snapshot() != snap



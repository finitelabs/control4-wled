class Device:
    def __init__(self, profile, clock=None, on_node_info=None):
        self.profile = profile
        self.version = profile["firmware"]
        if self.version not in FIRMWARE:
            raise ValueError(f"unsupported firmware {self.version}")
        self.v16 = self.version == "16.0.1"
        self.fw = FIRMWARE[self.version]
        self.chip_name = profile["chip"]
        self.chip = CHIPS[self.chip_name]
        self.psram = bool(profile.get("psram", False))
        data = load_data(self.version, self.chip["effects"])
        self.eff, self.fxdata, self.pal = data["eff"], data["fxdata"], data["pal"]
        self.fxmeta = data["fxmeta"]
        self.clock = clock or MonotonicClock()
        self.on_node_info = on_node_info
        self.max_segments = max_segments(self.version, self.chip_name, self.psram)
        self.ws_clients_max = profile.get("ws_clients", self.chip["ws_clients"])
        self.ws_frame_max = self.chip["ws_frame"]
        self.matrix = profile.get("matrix")
        self.mac = profile["mac"].lower().replace(":", "")
        self.ip = profile.get("ip", "")
        self.custom_palettes = int(profile.get("custom_palettes", 0))
        self.presets = {"0": {}}
        for pid, p in profile.get("presets", {}).items():
            self.presets[str(pid)] = copy.deepcopy(p)
        self.ws_count = lambda: 0
        self.push_due = False
        self.busy_until = 0
        self.boots = 0
        self.boot()

    # ---- boot and settings -------------------------------------------------------------------

    def boot(self):
        """Power-up state: WLED keeps cfg.json and presets.json, nothing else."""
        p, now = self.profile, self.clock.ms()
        boot = p.get("boot", {})
        self.boots += 1
        self.boot_ms = now
        self.buses = [Bus(b) for b in p["buses"]]
        white = p.get("white", {})
        self.global_awm = white.get("rgbwm", AW_GLOBAL_DISABLED)
        self.correct_wb = bool(white.get("correct_wb", False))
        self.cct_from_rgb = bool(white.get("cct_from_rgb", False))
        self.cct_blend = white.get("cct_blend", 0)
        self.crossfade = bool(p.get("crossfade", True)) or self.v16
        self.name = p.get("name", "WLED")
        self.total = max(b.start + b.len for b in self.buses)
        self.width = self.matrix["w"] if self.matrix else self.total
        self.height = self.matrix["h"] if self.matrix else 1

        # wled.cpp beginStrip: turnOnAtBoot sets bri to briS, otherwise briLast takes briS.
        self.bri_s = boot.get("bri", 128)
        self.bri = self.bri_s if boot.get("on", True) else 0
        self.bri_last, self.bri_old, self.bri_t = self.bri_s, 0, 0
        self.transition_delay = (boot.get("transition", 7) * 100) & 0xFFFF
        self.strip_transition = self.transition_delay if self.crossfade else 0
        self.json_transition_once = False
        self.transition_active = False
        self.transition_start = now
        # Whether the command being applied sets bri or tt, and whether a fade jumped on 16.x.
        self.fade_command = False
        self.fade_jumped = False
        # Calls that put a running color fade at its target at once, a visible jump.
        self.color_jumps = 0
        self.blending_style = 0
        self.state_changed = False

        color = self.fw["boot_color"]
        segs = p.get("segments") or [{"start": 0, "stop": self.width}]
        self.segments = []
        for s in segs[: self.max_segments]:
            seg = Segment(
                s["start"],
                s["stop"],
                s.get("startY", 0),
                s.get("stopY", self.height),
                color,
            )
            if "n" in s:
                seg.name = s["n"]
            if "col" in s:
                seg.colors = [rgbw32(*(list(c) + [0] * (4 - len(c)))) for c in s["col"]]
            seg.mode = s.get("fx", 0)
            self.segments.append(seg)
        self.main_segment = 0

        self.current_preset, self.preset_cyc_curr = 0, 0
        self.preset_to_apply = self.call_mode_to_apply = self.preset_to_save = 0
        self.save_name, self.quick_load = None, None
        self.include_bri = self.seg_bounds = True
        self.selected_only = self.playlist_save = False
        self.boot_preset = boot.get("preset", 0)

        self.current_playlist = -1
        self.pl_entries, self.pl_index, self.pl_repeat = [], -1, 1
        self.pl_end_preset, self.pl_options, self.pl_entry_dur = 0, 0, 0
        self.pl_cycled = now
        self.pl_parent_index, self.pl_parent_repeat, self.pl_parent_preset = -1, 0, 0
        self.do_advance = False

        self.nl_active = self.nl_active_old = False
        self.nl_dur, self.nl_mode, self.nl_tbri = 60, NL_MODE_FADE, 0
        self.nl_start = self.nl_delay_ms = self.nl_bri_t = 0
        self.nl_last = 0
        self.nl_col = [0, 0, 0, 0]

        self.udp_send, self.sync_groups, self.receive_groups = False, 1, 1
        self.realtime_mode, self.realtime_ip, self.realtime_override = None, "", 0
        self.realtime_timeout = 0
        self.realtime_stop_at = None
        self.output_bri_override = None
        self.second_toggle_at = None
        self.bus_change_pending = False

        self.error_flag = ERR_NONE
        self.do_reboot = False
        self.pmt = 0
        self.clock_offset = int(time.time()) * 1000 - now if p.get("ntp", False) else -now

        self.interface_update_call_mode = CALL_MODE_INIT
        self.last_interface_update = now - INTERFACE_UPDATE_COOLDOWN

        if self.boot_preset:
            self.apply_preset(self.boot_preset, CALL_MODE_INIT)
        self.state_updated(CALL_MODE_INIT)

    def set_bus(self, index, rgbwm=None, at_restart=False):
        """A white mode saved in the LED settings, kept across restarts like cfg.json. Saved over
        /json/cfg it shows only after the next restart."""
        if rgbwm is None:
            return
        self.profile["buses"] = copy.deepcopy(self.profile["buses"])
        self.profile["buses"][index]["rgbwm"] = rgbwm
        if not at_restart:
            self.buses[index].rgbwm = rgbwm
        elif rgbwm != self.buses[index].rgbwm:
            # Until the restart a dig2go on 0.15.4 read info.leds.rgbw false, bits unchanged.
            self.bus_change_pending = True

    def set_white(self, rgbwm=None, correct_wb=None, cct_from_rgb=None, at_restart=False):
        white = dict(self.profile.get("white", {}))
        for key, value in (
            ("rgbwm", rgbwm),
            ("correct_wb", correct_wb),
            ("cct_from_rgb", cct_from_rgb),
        ):
            if value is not None:
                white[key] = value
        self.profile["white"] = white
        if at_restart:
            return
        if rgbwm is not None:
            self.global_awm = rgbwm
        if correct_wb is not None:
            self.correct_wb = bool(correct_wb)
        if cct_from_rgb is not None:
            self.cct_from_rgb = bool(cct_from_rgb)

    # ---- time and the shared JSON buffer -----------------------------------------------------

    def now(self):
        return self.clock.ms()

    def seconds(self):
        """toki.second(): unix time with NTP, else seconds since boot unless a client set it."""
        return max(0, (self.now() + self.clock_offset) // 1000)

    def set_time(self, unix_seconds):
        self.clock_offset = unix_seconds * 1000 - self.now()

    def busy_for(self):
        return max(0, self.busy_until - self.now())

    def make_busy(self, ms):
        self.busy_until = self.now() + ms

    # ---- capabilities ------------------------------------------------------------------------

    def seg_lc(self, seg):
        """Segment::refreshLightCapabilities (FX_fcn.cpp)."""
        if not seg.is_active():
            return 0
        lo = seg.start + self.width * seg.start_y
        hi = (seg.stop - 1) + self.width * (seg.stop_y - 1) + 1
        caps = 0
        for b in self.buses:
            if b.start >= hi or b.start + b.len <= lo:
                continue
            t = b.type
            cct = bus_has_cct(t, self.v16)
            if bus_has_rgb(t) or (self.cct_from_rgb and cct):
                caps |= CAP_RGB
            if not self.cct_from_rgb and cct:
                caps |= CAP_CCT
            if self.correct_wb and (bus_has_rgb(t) or cct):
                caps |= CAP_CCT
            if bus_has_white(t):
                awm = b.rgbwm if self.global_awm == AW_GLOBAL_DISABLED else self.global_awm
                caps |= CAP_W if awm in (RGBW_MODE_DUAL, RGBW_MODE_MANUAL_ONLY) else CAP_RGB
        return caps

    def has_white_channel(self):
        return any(bus_has_white(b.type) for b in self.buses)

    def has_rgbw_bus(self):
        if self.bus_change_pending:
            return False
        return any(bus_has_rgb(b.type) and bus_has_white(b.type) for b in self.buses)

    def mode_count(self):
        return len(self.eff)

    def palette_count(self):
        return self.fw["fixed_palettes"] + self.custom_palettes

    # ---- segments ----------------------------------------------------------------------------

    def last_active_segment(self):
        for i in range(len(self.segments) - 1, 0, -1):
            if self.segments[i].is_active():
                return i
        return 0

    def set_main_segment_id(self, n):
        self.main_segment = self.last_active_segment()
        if n < len(self.segments) and self.segments[n].is_active():
            self.main_segment = n

    def purge_segments(self):
        if len(self.segments) <= 1:
            return
        deleted = 0
        for i in range(len(self.segments) - 1, 0, -1):
            if self.segments[i].stop == 0:
                del self.segments[i]
                deleted += 1
        if deleted:
            self.set_main_segment_id(0)

    def set_geometry(self, seg, i1, i2, grp, spc, ofs, i1y, i2y, m12):
        """Segment::setGeometry; 0.15.4 flags a state change on every call."""
        unchanged = seg.start == i1 and seg.stop == i2
        if self.v16 or self.height > 1:
            unchanged = unchanged and seg.start_y == i1y and seg.stop_y == i2y
        if self.v16:
            unchanged = unchanged and seg.grouping == grp and seg.spacing == spc
        else:
            self.state_changed = True
        if grp:
            seg.grouping, seg.spacing = grp, spc
        else:
            seg.grouping, seg.spacing = 1, 0
        if ofs < 0xFFFF:
            seg.offset = ofs
        seg.map1d2d = max(0, min(7, m12))
        if unchanged:
            return
        seg.reset = True
        self.state_changed = True
        if i2 <= i1:
            seg.stop = 0
            return
        w, h = self.width, self.height
        if i1 < w or (w * h <= i1 < self.total):
            seg.start = i1
        if self.v16:
            trailing = i2 > w * h and i1 >= w * h
            seg.stop = min(i2, self.total) if trailing else max(1, min(i2, w))
        else:
            seg.stop = min(i2, self.total) if i2 > w * h else (w if i2 > w else max(1, i2))
        seg.start_y, seg.stop_y = 0, 1
        if h > 1:
            if i1y < h:
                seg.start_y = i1y
            seg.stop_y = max(1, min(i2y, h))
        if seg.start >= seg.stop or seg.start_y >= seg.stop_y:
            seg.stop = 0

    def set_option_on(self, seg, val):
        if seg.on != val:
            seg.on = val
            self.state_changed = True

    def set_opacity(self, seg, o):
        if seg.opacity != o:
            seg.opacity = o
            self.state_changed = True

    def set_cct(self, seg, k):
        if k > 255:
            k = (max(1900, min(10091, k)) - 1900) >> 5
        if seg.cct != k:
            seg.cct = k
            self.state_changed = True

    def set_color(self, seg, slot, c):
        if slot >= 3 or c == seg.colors[slot]:
            return
        lc = self.seg_lc(seg)
        if not (lc & CAP_RGB) and not (lc & CAP_W):
            if slot == 0 and c == 0:
                return
            if slot == 1 and c != 0:
                return
        self.start_color_transition(seg, slot, c)
        seg.colors[slot] = c
        self.state_changed = True

    def color_progress(self, seg):
        """How far a segment's color transition has got, 0 to 1; 1 with none running."""
        if seg.t_from is None or seg.t_dur <= 0:
            return 1.0
        return min(1.0, (self.now() - seg.t_start) / seg.t_dur)

    def output_color(self, seg, slot=0):
        """The color a segment shows now, part way through its transition."""
        to = channels(seg.colors[slot])
        p = self.color_progress(seg)
        if p >= 1.0:
            return to
        fr = channels(seg.t_from[slot])
        return [int(fr[i] + (to[i] - fr[i]) * p) for i in range(4)]

    def start_color_transition(self, seg, slot=0, c=None):
        """FX_fcn.cpp Segment::startTransition, called before a color changes. 16.x captures where a
        running transition has got to and restarts it; 0.15.4 leaves a running one its start values
        and timer, so the new color is reached on the old schedule (FX_fcn.cpp:271@v0.15.4).
        """
        dur = self.strip_transition if self.crossfade else 0
        if dur <= 0:
            seg.t_from = None
            return
        if self.v16 and slot == 0 and c is not None:
            # Measured on the dig2go, 2026-11-12: on 16.0.1 a fade from the white LEDs alone to an RGB
            # color alone ([0,0,0,255] to [255,0,0,0], tt 30) lands within a frame.
            fr, to = channels(seg.colors[0]), channels(c)
            if fr[:3] == [0, 0, 0] and fr[3] > 0 and to[3] == 0 and max(to[:3]) > 0:
                seg.t_from = None
                return
        running = self.color_progress(seg) < 1.0
        if running and not self.v16:
            return
        seg.t_from = [rgbw32(*self.output_color(seg, i)) for i in range(3)]
        seg.t_start, seg.t_dur = self.now(), dur

    def stop_color_transitions(self, jumped=False):
        """WS2812FX::setTransitionMode(false): every segment at its colors at once. jumped counts it
        when a color still part way moves at once by more than the wire's rounding."""
        moved = False
        for seg in self.segments:
            if self.color_progress(seg) < 1.0:
                now_col, to = self.output_color(seg), channels(seg.colors[0])
                moved = moved or max(abs(a - b) for a, b in zip(now_col, to)) > 2
            seg.t_from = None
        if jumped and moved:
            self.color_jumps += 1

    def set_palette(self, seg, pal):
        if self.v16:
            fixed = self.fw["fixed_palettes"]
            if pal >= fixed:
                if pal > 200:
                    pal = 0  # no usermod palettes in the mock
                elif 200 - pal >= self.custom_palettes:
                    pal = 0
        else:
            if 71 < pal < 245:
                pal = 0
            if pal > 245 and (self.custom_palettes == 0 or 255 - pal > self.custom_palettes - 1):
                pal = 0
        if pal != seg.palette:
            seg.palette = pal
            self.state_changed = True

    def mode_default(self, fx, key):
        """util.cpp extractModeDefaults."""
        data = self.fxdata[fx] if fx < len(self.fxdata) else ""
        if ";" not in data:
            return -1
        tail = data[data.rindex(";") :]
        i = tail.find(key)
        if i < 0:
            return -1
        return _atoi(tail[i + len(key) + 1 :])

    def set_mode(self, seg, fx, load_defaults):
        """Segment::setMode: a reserved id moves on to the next real effect."""
        while fx < self.mode_count() and self.eff[fx] == "RSVD":
            fx += 1
        if fx >= self.mode_count():
            fx = 0
        if fx == seg.mode:
            return
        seg.mode = fx
        if load_defaults:
            for key, attr, dflt in (
                ("sx", "speed", 128),
                ("ix", "intensity", 128),
                ("c1", "custom1", 128),
                ("c2", "custom2", 128),
                ("c3", "custom3", 16),
            ):
                v = self.mode_default(fx, key)
                setattr(seg, attr, v if v >= 0 else dflt)
            for key, attr in (("o1", "check1"), ("o2", "check2"), ("o3", "check3")):
                v = self.mode_default(fx, key)
                setattr(seg, attr, bool(v) if v >= 0 else False)
            v = self.mode_default(fx, "m12")
            seg.map1d2d = max(0, min(7, v)) if v >= 0 else 0
            v = self.mode_default(fx, "si")
            if v >= 0:
                seg.sound_sim = max(0, min(3, v))
            pal = self.mode_default(fx, "pal")
            if pal >= 0:
                self.set_palette(seg, pal)
        seg.reset = True
        self.state_changed = True

    def deserialize_segment(self, elem, it, preset_id=0):
        """json.cpp deserializeSegment."""
        sid = pipe_u8(elem.get("id"), it)
        if sid >= self.max_segments:
            return False
        new_seg = False
        stop = pipe_int(elem.get("stop"), -1)
        if sid >= len(self.segments):
            if stop <= 0:
                return False
            if len(self.segments) < self.max_segments:
                color = 0 if self.v16 else self.fw["default_color"]
                self.segments.append(Segment(0, self.total, 0, self.height, color))
            sid = len(self.segments) - 1
            new_seg = True
        seg = self.segments[sid]
        if new_seg and preset_id == 0 and self.v16:
            seg.colors[0] = self.fw["default_color"]
        prev = seg.snapshot()

        start = pipe_int(elem.get("start"), seg.start)
        if stop < 0:
            ln = pipe_int(elem.get("len"), 0)
            stop = start + ln if ln > 0 else seg.stop
        start_y = pipe_int(elem.get("startY"), seg.start_y)
        stop_y = pipe_int(elem.get("stopY"), seg.stop_y)

        if pipe_bool(elem.get("rpt"), False) and stop > 0:
            for k in ("id", "rpt", "n"):
                elem.pop(k, None)
            ln = stop - start
            for i in range(sid + 1, self.max_segments):
                start += ln
                if start >= self.total:
                    break
                elem["start"], elem["stop"] = start, start + ln
                elem["rev"] = not truthy(elem.get("rev"))
                self.deserialize_segment(elem, i, preset_id)
            return True

        n = elem.get("n")
        if n is not None and n is not False and n != 0:
            seg.name = n[:32] if isinstance(n, str) and n else None
        elif start != seg.start or stop != seg.stop:
            seg.name = None

        grp = pipe_u16(elem.get("grp"), seg.grouping)
        spc = pipe_u16(elem.get("spc"), seg.spacing)
        of = seg.offset
        sound_sim = pipe_u8(elem.get("si"), seg.sound_sim)
        m12 = pipe_u8(elem.get("m12"), seg.map1d2d)
        set_ = pipe_u8(elem.get("set"), seg.set)
        selected = get_bool_val(elem.get("sel"), seg.selected)
        reverse = get_bool_val(elem.get("rev"), seg.reverse)
        mirror = get_bool_val(elem.get("mi"), seg.mirror)
        reverse_y = get_bool_val(elem.get("rY"), seg.reverse_y)
        mirror_y = get_bool_val(elem.get("mY"), seg.mirror_y)
        transpose = get_bool_val(elem.get("tp"), seg.transpose)

        ln = stop - start if stop > start else 1
        offset = pipe_int(elem.get("of"), INT32_MAX)
        if offset != INT32_MAX:
            off = abs(offset)
            if off > ln - 1:
                off %= ln
            if offset < 0:
                off = ln - off
            of = off
        if stop > start and of > ln - 1:
            of = ln - 1

        self.set_geometry(seg, start, stop, grp, spc, of, start_y, stop_y, m12)
        if seg.reset and seg.stop == 0:
            if sid == self.main_segment:
                self.set_main_segment_id(0)
            return True

        found, segbri = get_val(elem.get("bri"), seg.opacity)
        if found:
            if segbri > 0:
                self.set_opacity(seg, segbri)
            self.set_option_on(seg, segbri > 0)
        self.set_option_on(seg, get_bool_val(elem.get("on"), seg.on))
        seg.freeze = get_bool_val(elem.get("frz"), seg.freeze)
        self.set_cct(seg, pipe_u16(elem.get("cct"), seg.cct))

        colarr = elem.get("col")
        if isinstance(colarr, list):
            if self.seg_lc(seg) & 3:
                for i in range(3):
                    rgbw = self._parse_color(colarr[i] if i < len(colarr) else None, seg, i)
                    if rgbw is not None:
                        self.set_color(seg, i, rgbw32(*rgbw))
            else:
                self.set_color(seg, 0, ULTRAWHITE)
                self.set_color(seg, 1, 0)

        seg.set = max(0, min(3, set_))
        seg.sound_sim = max(0, min(3, sound_sim))
        seg.selected, seg.reverse, seg.mirror = selected, reverse, mirror
        seg.reverse_y, seg.mirror_y, seg.transpose = reverse_y, mirror_y, transpose

        found, fx = get_val(elem.get("fx"), seg.mode, 0, self.mode_count())
        if found:
            if not preset_id and self.current_playlist >= 0:
                self.unload_playlist()
            if fx != seg.mode:
                self.set_mode(seg, fx, truthy(elem.get("fxdef")))
        _, seg.speed = get_val(elem.get("sx"), seg.speed)
        _, seg.intensity = get_val(elem.get("ix"), seg.intensity)
        if self.seg_lc(seg) & CAP_RGB:
            found, pal = get_val(elem.get("pal"), seg.palette, 0, self.palette_count())
            if found:
                self.set_palette(seg, pal)
        _, seg.custom1 = get_val(elem.get("c1"), seg.custom1)
        _, seg.custom2 = get_val(elem.get("c2"), seg.custom2)
        _, c3 = get_val(elem.get("c3"), seg.custom3, 0, 31)
        seg.custom3 = max(0, min(31, c3))
        seg.check1 = get_bool_val(elem.get("o1"), seg.check1)
        seg.check2 = get_bool_val(elem.get("o2"), seg.check2)
        seg.check3 = get_bool_val(elem.get("o3"), seg.check3)
        if self.v16:
            _, seg.blend_mode = get_val(elem.get("bm"), seg.blend_mode)
        if isinstance(elem.get("i"), list):
            self.json_transition_once = True
            self.strip_transition = 0
            seg.freeze = True
        if seg.differs(prev):
            self.state_changed = True
        return True

    def _parse_color(self, v, seg, slot):
        """One entry of a segment's "col": array, object, hex string, Kelvin or 0."""
        if isinstance(v, list):
            if not v:
                return None
            out = [0, 0, 0, 0]
            for i, x in enumerate(v[:4]):
                out[i] = int(x) if isinstance(x, (int, float)) and not isinstance(x, bool) else 0
            return out
        if isinstance(v, dict):
            cur = channels(seg.colors[slot])
            return [pipe_int(v.get(k), cur[i]) for i, k in enumerate("rgbw")]
        if isinstance(v, str):
            if self.v16 and v == "r":
                return [random.randint(0, 255) for _ in range(3)] + [0]
            return color_from_hex(v)
        if _is_int(v):
            if v < 0:
                return None
            if v == 0:
                self.set_color(seg, slot, 0)
                return [0, 0, 0, 0]
            return color_k_to_rgb(v)
        return None

    # ---- state -------------------------------------------------------------------------------

    def toggle_on_off(self):
        """led.cpp toggleOnOff."""
        if self.bri == 0:
            self.bri = self.bri_last
        else:
            self.bri_last = self.bri
            self.bri = 0
        self.state_changed = True

    def apply_final_bri(self):
        self.bri_old = self.bri_t = self.bri
        self.fade_jumped = False

    def state_updated(self, call_mode):
        """led.cpp stateUpdated."""
        now = self.now()
        changed = self.bri != self.bri_old or self.state_changed
        if changed:
            if self.state_changed:
                self.current_preset = 0
            if self.bri != self.bri_old and self.on_node_info:
                self.on_node_info()
            self.interface_update_call_mode = call_mode
        elif (
            self.nl_active
            and not self.nl_active_old
            and call_mode not in (CALL_MODE_NOTIFICATION, CALL_MODE_NO_NOTIFY)
        ):
            self.interface_update_call_mode = CALL_MODE_NIGHTLIGHT
        if (
            call_mode != CALL_MODE_NO_NOTIFY
            and self.nl_active
            and self.nl_mode in (NL_MODE_FADE, NL_MODE_COLORFADE)
        ):
            self.nl_bri_t = self.bri
            self.nl_delay_ms -= now - self.nl_start
            self.nl_start = now
        if self.bri > 0:
            self.bri_last = self.bri
        if (
            self.bri == self.nl_tbri
            and call_mode != CALL_MODE_NO_NOTIFY
            and self.nl_mode != NL_MODE_SUN
        ):
            self.nl_active = False
        if not self.crossfade:
            self.apply_final_bri()
        elif self.strip_transition == 0:
            self.json_transition_once = False
            self.transition_active = False
            self.apply_final_bri()
        else:
            if self.transition_active:
                self.bri_old = self.bri_t
                # 16.x jumps at once to the target of a fade that arrives while another runs,
                # brightness and every segment's color alike (measured on a dig2go, 2026-11-11 and
                # 11-12); 0.15 fades brightness on from where the output is.
                if self.v16 and self.fade_command:
                    self.fade_jumped = True
                    self.stop_color_transitions(jumped=True)
            self.transition_active = True
            self.transition_start = now
        self.state_changed = False

    def deserialize_state(self, root, call_mode=CALL_MODE_DIRECT_CHANGE, preset_id=0):
        """json.cpp deserializeState: returns whether the caller asked for a verbose reply."""
        if not isinstance(root, dict):
            root = {}
        for seg in self.segments:
            seg.reset = False
        state_response = pipe_bool(root.get("v"), False)
        self.fade_command = root.get("bri") is not None or root.get("tt") is not None
        on_before = self.bri > 0
        _, self.bri = get_val(root.get("bri"), self.bri)
        if self.v16 and self.bri != self.bri_old:
            self.state_changed = True
        on = pipe_bool(root.get("on"), self.bri > 0)
        if (not on) != (not self.bri):
            self.toggle_on_off()
        if isinstance(root.get("on"), str) and root["on"][:1] == "t":
            if on_before or not self.bri:
                self.toggle_on_off()
        if self.bri and not on_before:
            for seg in self.segments:
                seg.freeze = False

        if not preset_id or self.current_playlist < 0:
            tr = pipe_int(root.get("transition"), -1)
            if tr >= 0:
                self.transition_delay = (tr * 100) & 0xFFFF
                if self.crossfade:
                    self.strip_transition = self.transition_delay
        if self.v16:
            self.blending_style = pipe_u8(root.get("bs"), self.blending_style) & 0x1F
        tr = pipe_int(root.get("tt"), -1)
        if tr >= 0:
            self.json_transition_once = True
            if self.crossfade:
                self.strip_transition = (tr * 100) & 0xFFFF

        nl = root.get("nl")
        if isinstance(nl, dict):
            if self.v16:
                self.state_changed = True
        else:
            nl = {}
        self.nl_active = get_bool_val(nl.get("on"), self.nl_active)
        self.nl_dur = pipe_u8(nl.get("dur"), self.nl_dur)
        self.nl_mode = pipe_u8(nl.get("mode"), self.nl_mode)
        self.nl_tbri = pipe_u8(nl.get("tbri"), self.nl_tbri)

        udpn = root.get("udpn") if isinstance(root.get("udpn"), dict) else {}
        self.udp_send = get_bool_val(udpn.get("send"), self.udp_send)
        self.sync_groups = pipe_u8(udpn.get("sgrp"), self.sync_groups)
        self.receive_groups = pipe_u8(udpn.get("rgrp"), self.receive_groups)
        if truthy(udpn.get("nn")):
            call_mode = CALL_MODE_NO_NOTIFY

        timein = pipe_int(root.get("time"), UINT32_MAX, 0, UINT32_MAX)
        if timein != UINT32_MAX:
            self.set_time(timein)
            if self.pmt == 0:
                self.pmt = timein

        if root.get("psave") is None:
            self.do_reboot = pipe_bool(root.get("rb"), self.do_reboot)

        if not self.realtime_mode:
            self.set_main_segment_id(pipe_u8(root.get("mainseg"), self.main_segment))
        self.realtime_override = pipe_u8(root.get("lor"), self.realtime_override)
        if self.realtime_override > 2:
            self.realtime_override = 2

        if "live" in root:
            if truthy(root["live"]):
                self.json_transition_once = True
                self.strip_transition = 0
                self.realtime_lock(65000, "generic")
            else:
                self.exit_realtime()

        seg_var = root.get("seg")
        if isinstance(seg_var, dict):
            sid = pipe_int(seg_var.get("id"), -1)
            if sid < 0:
                for s in range(len(self.segments)):
                    sg = self.segments[s]
                    if sg.is_active() and sg.selected:
                        self.deserialize_segment(seg_var, s, preset_id)
            else:
                self.deserialize_segment(seg_var, sid, preset_id)
        elif isinstance(seg_var, list):
            deleted = 0
            for it, elem in enumerate(seg_var):
                elem = elem if isinstance(elem, dict) else {}
                if self.deserialize_segment(elem, it, preset_id) and elem.get("stop", None) == 0:
                    deleted += 1
            if len(self.segments) > 3 and deleted >= len(self.segments) // 2:
                self.purge_segments()

        if self.v16 and pipe_bool(root.get("rSeg"), False):
            self.make_auto_segments()
            self.state_changed = True

        ps = as_u8(root.get("psave"))
        if 0 < ps < 251:
            self.save_preset(ps, None, root)
        ps = as_u8(root.get("pdel"))
        if 0 < ps < 251:
            self.delete_preset(ps)

        preset_to_restore = 0
        if root.get("pd") is not None and self.state_changed:
            self.current_preset = pipe_u8(root["pd"], self.current_preset)
            if root.get("win") is None:
                self.preset_cyc_curr = self.current_preset
            preset_to_restore = self.current_preset
        elif root.get("ps") is not None:
            found, val = get_val(root["ps"], self.preset_cyc_curr, 1, 250)
            self.preset_cyc_curr = val
            if root.get("win") is None and found and 0 < val < 251 and val != self.current_preset:
                self.apply_preset(val, call_mode)
                self.fade_command = False
                return state_response
            self.preset_cyc_curr = self.current_preset

        playlist = root.get("playlist")
        if isinstance(playlist, dict):
            # loadPlaylist returns the preset id (0 when sent directly) or -1, and WLED tests it
            # for truth, so a direct playlist leaves the call mode alone.
            if self.load_playlist(playlist, preset_id):
                call_mode = (
                    CALL_MODE_NO_NOTIFY if root.get("on") is None else CALL_MODE_DIRECT_CHANGE
                )

        self.do_advance = pipe_bool(root.get("np"), self.do_advance)

        if not self.v16 or self.state_changed:
            self.state_updated(call_mode)
        self.fade_command = False
        if preset_to_restore:
            self.current_preset = preset_to_restore
        return state_response

    def make_auto_segments(self):
        """rSeg: one segment per bus when the profile asks for auto segments, else one."""
        color = self.fw["default_color"]
        if self.profile.get("auto_segments", False):
            self.segments = [Segment(b.start, b.start + b.len, 0, 1, color) for b in self.buses]
        else:
            self.segments = [Segment(0, self.width, 0, self.height, color)]
        self.main_segment = 0

    def serialize_segment(self, seg, sid, for_preset, bounds):
        out = {"id": sid}
        if bounds:
            out["start"], out["stop"] = seg.start, seg.stop
            if self.matrix:
                out["startY"], out["stopY"] = seg.start_y, seg.stop_y
        if not for_preset:
            out["len"] = seg.stop - seg.start
        out.update(grp=seg.grouping, spc=seg.spacing, of=seg.offset, on=seg.on, frz=seg.freeze)
        out["bri"] = seg.opacity or 255
        out["cct"] = seg.cct
        out["set"] = seg.set
        if self.v16:
            out["lc"] = self.seg_lc(seg)
        if seg.name is not None:
            out["n"] = seg.name
        elif for_preset:
            out["n"] = ""
        width = 4 if self.has_white_channel() else 3
        out["col"] = [channels(c)[:width] for c in seg.colors]
        out.update(fx=seg.mode, sx=seg.speed, ix=seg.intensity, pal=seg.palette)
        out.update(c1=seg.custom1, c2=seg.custom2, c3=seg.custom3)
        out.update(sel=seg.selected, rev=seg.reverse, mi=seg.mirror)
        if self.matrix:
            out.update(rY=seg.reverse_y, mY=seg.mirror_y, tp=seg.transpose)
        out.update(
            o1=seg.check1,
            o2=seg.check2,
            o3=seg.check3,
            si=seg.sound_sim,
            m12=seg.map1d2d,
        )
        if self.v16:
            out["bm"] = seg.blend_mode
        return out

    def serialize_state(self, for_preset=False, include_bri=True, bounds=True, selected_only=False):
        """json.cpp serializeState."""
        out = {}
        if include_bri:
            out["on"] = self.bri > 0
            out["bri"] = self.bri_last
            out["transition"] = self.transition_delay // 100
            if self.v16:
                out["bs"] = self.blending_style
        if not for_preset:
            if self.error_flag:
                out["error"] = self.error_flag
                self.error_flag = ERR_NONE
            out["ps"] = self.current_preset if self.current_preset > 0 else -1
            out["pl"] = self.current_playlist
            out["ledmap"] = 0
            rem = -1
            if self.nl_active:
                rem = int((self.nl_delay_ms - (self.now() - self.nl_start)) / 1000)
            out["nl"] = {
                "on": self.nl_active,
                "dur": self.nl_dur,
                "mode": self.nl_mode,
                "tbri": self.nl_tbri,
                "rem": rem,
            }
            out["udpn"] = {
                "send": self.udp_send,
                "recv": self.receive_groups != 0,
                "sgrp": self.sync_groups,
                "rgrp": self.receive_groups,
            }
            out["lor"] = self.realtime_override
        out["mainseg"] = self.main_segment
        segs = []
        for s in range(self.max_segments):
            if s >= len(self.segments):
                if for_preset and bounds and not selected_only:
                    segs.append({"stop": 0})
                    continue
                break
            sg = self.segments[s]
            if for_preset and selected_only and not sg.selected:
                continue
            if sg.is_active():
                segs.append(self.serialize_segment(sg, s, for_preset, bounds))
            elif for_preset and bounds:
                segs.append({"stop": 0})
        out["seg"] = segs
        return out

